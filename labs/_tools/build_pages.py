    spec = json.loads((REF / "safeguards_reference.json").read_text(encoding="utf-8"))
    with open(FILES / "d1_2" / "drafts_v11.csv", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    out = []
    for s in spec["safeguards"]:
        res = []
        for t in s["tests"]:
            ok, head, lines = run_tests.run_test(t, rows)
            fails = [ln.strip().replace(" FAIL", "") for ln in lines if "FAIL" in ln or "too few" in ln]
            res.append(("اجتياز" if ok else "إخفاق") + (": " + "، ".join(fails) if fails else ""))
        out.append({"id": s["id"], "harm": s["harm"], "what": s["requirement"], "result": "؛ ".join(res)})
    return out


